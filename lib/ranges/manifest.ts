export function findChart(
  format: string,
  stack: number,
  position: string,
  vs_action: string,
  vs_position?: string
): RangeChart | undefined {
  return ALL_RANGE_CHARTS.find(
    (c) =>
      c.format === format &&
      c.stack === stack &&
      c.position === position &&
      c.vs_action === vs_action &&
      (vs_position ? c.vs_position === vs_position : !c.vs_position)
  )
}

// Backwards compat : old signature (position, vs_action, vs_position?) — defaults cash_6max 100bb
export function findChartLegacy(
  position: string,
  vs_action: string,
  vs_position?: string
): RangeChart | undefined {
  return findChart("cash_6max", 100, position, vs_action, vs_position)
}
